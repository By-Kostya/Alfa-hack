def full_text(plan: dict) -> str:
    parts = [plan["title"], plan["subtitle"]]
    for heading, paragraphs in plan["sections"]:
        parts.append(heading)
        parts.extend(paragraphs)
    return "\n".join(parts)


def check_plan(plan: dict) -> None:
    text = full_text(plan)
    quote = plan["quote"]
    if quote not in text:
        raise SystemExit(f"{plan['file']}: цитаты нет в тексте")
    if text.count(quote) != 1:
        raise SystemExit(f"{plan['file']}: цитата встречается {text.count(quote)} раз")
    flow = eval(plan["flow_formula"], {"__builtins__": {}})
    if int(flow) != flow or int(flow) != plan["inferred_monthly_flow_rub"]:
        raise SystemExit(f"{plan['file']}: формула дала {flow}, в золоте {plan['inferred_monthly_flow_rub']}")
    missing = [n for n in standalone_numbers(plan["flow_formula"]) if not has_token(quote, n)]
    if missing:
        raise SystemExit(f"{plan['file']}: в цитате нет чисел {missing}")
    count = len(words(text))
    plan["word_count"] = count
    if not 700 <= count <= 1200:
        raise SystemExit(f"{plan['file']}: {count} слов, нужно 700–1200")
    low = text.lower()
    found = [w for w in BANNED if w in low]
    if found:
        raise SystemExit(f"{plan['file']}: запрещённые слова {found}")
    if plan["loan_mark"] not in text:
        raise SystemExit(f"{plan['file']}: нет суммы кредита")
    if plan["first_money"] not in text:
        raise SystemExit(f"{plan['file']}: нет срока до первых денег")
    quote_low = quote.lower()
    if "выручк" not in quote_low or "расход" not in quote_low:
        raise SystemExit(f"{plan['file']}: в цитате нет выручки или расходов")
    if "\n" in quote or "\t" in quote:
        raise SystemExit(f"{plan['file']}: цитата не в одну строку текста")


def build_docx(plan: dict) -> None:
    doc = new_doc()
    add_text(doc, plan["title"], size=16, bold=True, align="center", indent=False, space_after=4)
    add_text(doc, plan["subtitle"], size=12, italic=True, align="center", indent=False, space_after=14)
    for heading, paragraphs in plan["sections"]:
        add_text(doc, heading, size=13, bold=True, align="left", indent=False, space_before=12, space_after=6)
        for paragraph in paragraphs:
            add_text(doc, paragraph, size=12, align="justify", indent=True, space_after=8)
    for section in doc.sections:
        add_footer(section, plan["footer"])
    core = doc.core_properties
    core.title = plan["title"]
    core.subject = plan["subtitle"]
    core.author = plan["footer"].split("  ·  ")[0]
    core.language = "ru-RU"
    path = ROOT / plan["file"]
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(path)

    saved = Document(path)
    body = "\n".join(p.text for p in saved.paragraphs)
    if plan["quote"] not in body:
        raise SystemExit(f"{plan['file']}: цитата не читается из docx")
    if plan["quote"] not in [p.text for p in saved.paragraphs]:
        raise SystemExit(f"{plan['file']}: цитата не совпала с абзацем docx")


def manifest_item(plan: dict) -> dict:
    return {
        "file": plan["file"],
        "kind": "plan",
        "business": plan["business"],
        "inferred_monthly_flow_rub": plan["inferred_monthly_flow_rub"],
        "flow_formula": plan["flow_formula"],
        "risks": plan["risks"],
        "quote": plan["quote"],
        "sustainable_loan_rub": plan["sustainable_loan_rub"],
    }


def main() -> None:
    if len(PLANS) != 7:
        raise SystemExit("нужно ровно семь планов")
    files = [p["file"] for p in PLANS]
    if len(set(files)) != 7:
        raise SystemExit("имена файлов повторяются")
    for plan in PLANS:
        check_plan(plan)
        build_docx(plan)
        print(f"{plan['file']}: {plan['word_count']} слов, поток {plan['inferred_monthly_flow_rub']}")

    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    data = [item for item in data if not str(item.get("file", "")).startswith("plans/long/")]
    data.extend(manifest_item(plan) for plan in PLANS)
    MANIFEST.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"manifest: {len(data)} записей")


if __name__ == "__main__":
    main()
