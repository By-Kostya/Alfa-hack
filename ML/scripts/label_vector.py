def match_one(text: str, rules: list, kind: str):
    hits = [rule for rule in rules if rule[0] in text]
    if len(hits) != 1:
        raise SystemExit(f"{kind}: {len(hits)} совпадений, начало {text[:80]!r}")
    return hits[0]


def main() -> None:
    gold: dict[str, list] = {}
    if GOLD.exists():
        with GOLD.open(encoding="utf-8") as handle:
            for line in handle:
                row = json.loads(line)
                gold[row["id"]] = row["llm_vector"]

    count = 0
    diffs = 0
    with TASKS.open(encoding="utf-8") as source, OUT.open("w", encoding="utf-8") as target:
        for line in source:
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            plan = match_one(row["plan_text"], PLAN_RULES, "plan")
            contract = match_one(row["contract_text"], CONTRACT_RULES, "contract")
            _, months, use, context, quote_months, quote_use, quote_context = plan
            _, has_contract, quote_contract = contract
            for quote, src, name in (
                (quote_months, row["plan_text"], "months"),
                (quote_use, row["plan_text"], "use"),
                (quote_context, row["plan_text"], "context"),
                (quote_contract, row["contract_text"], "contract"),
            ):
                if quote and quote not in src:
                    raise SystemExit(f"цитата {name} не найдена в {row['id']}")
            vector = [months, has_contract, use, context]
            if gold and gold.get(row["id"]) != vector:
                diffs += 1
                if diffs <= 5:
                    print(row["id"], vector, gold.get(row["id"]))
            obj = {
                "id": row["id"],
                "llm_vector": vector,
                "quotes": {
                    "months_to_first_cashflow": quote_months,
                    "has_contract": quote_contract,
                    "use_of_funds": quote_use,
                    "context_specific": quote_context,
                },
            }
            target.write(json.dumps(obj, ensure_ascii=False) + "\n")
            count += 1
    print(f"rows {count} diffs {diffs}")
    print(OUT)


if __name__ == "__main__":
    main()
